"""Generate Claude discovery pointers from the authoritative .agents skills.

The skill inventory and raw frontmatter belong to .agents/skills; discovery
entries are a projection, never another maintained procedure. Adding a skill
there automatically adds a pointer here. This uses only the standard library
so a fresh checkout can check or regenerate pointers before installing the app.

Only marked generated files and empty adapter directories belong to this tool.
Preflight the whole tree before writing so a misplaced resource or an old full
skill cannot be overwritten halfway through a sync. Actual host discovery is
outside this file's contract; it produces ordinary, committed SKILL.md entries.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

GENERATED = "<!-- Generated by scripts/sync_skills.py; do not edit. -->"
_HEADER = re.compile(r"\A(---\n.*?\n---)(?:\n|\Z)", re.DOTALL)


def pointer_text(source: Path) -> str:
    """Copy YAML verbatim: folding, quoting and extra metadata must survive.

    The skills guard owns semantic validation. This renderer only separates
    the discovery header from the procedure, avoiding a second YAML parser.
    """
    match = _HEADER.match(source.read_text(encoding="utf-8"))
    if not match:
        raise ValueError(f"missing or malformed frontmatter: {source}")
    target = f"../../../.agents/skills/{source.parent.name}/SKILL.md"
    return (
        f"{match.group(1)}\n\n{GENERATED}\n\n"
        f"Read and follow the [authoritative procedure]({target}) in full.\n"
        "Follow relative links from the authoritative file that contains them.\n"
    )


def _expected_pointers(canonical: Path) -> dict[str, str]:
    if not canonical.is_dir():
        raise ValueError(f"missing authoritative skill directory: {canonical}")
    expected = {}
    for directory in sorted(canonical.iterdir()):
        if not directory.is_dir():
            continue
        source = directory / "SKILL.md"
        if source.resolve() != source:
            raise ValueError(f"authoritative skill must not be a link: {source}")
        expected[directory.name] = pointer_text(source)
    if not expected:
        raise ValueError(f"no authoritative skills found: {canonical}")
    return expected


def _existing_pointers(adapters: Path) -> dict[str, str | None]:
    existing = {}
    for directory in sorted(adapters.iterdir()) if adapters.exists() else ():
        pointer = directory / "SKILL.md"
        if (not directory.is_dir() or directory.resolve() != directory
                or pointer.resolve() != pointer):
            raise ValueError(f"unexpected file or link in discovery directory: {directory}")
        contents = {path.name for path in directory.iterdir()}
        if contents - {"SKILL.md"}:
            raise ValueError(f"discovery directory may contain only SKILL.md: {directory}")
        text = pointer.read_text(encoding="utf-8") if contents else None
        if text is not None and GENERATED not in text:
            raise ValueError(f"refusing to overwrite a non-generated skill: {pointer}")
        existing[directory.name] = text
    return existing


def sync(root: Path, *, write: bool = False) -> list[str]:
    """Report drift, optionally updating generated files after full preflight."""
    root = root.resolve()
    canonical = root / ".agents" / "skills"
    adapters = root / ".claude" / "skills"
    if canonical.resolve() != canonical or adapters.resolve() != adapters:
        raise ValueError("skill directories must belong to this checkout, without links")
    expected = _expected_pointers(canonical)
    existing = _existing_pointers(adapters)
    changes = []
    for name in sorted(expected.keys() | existing.keys()):
        pointer = adapters / name / "SKILL.md"
        if name not in expected:
            changes.append((pointer, None, "orphan pointer"))
        elif existing.get(name) != expected[name]:
            status = "missing pointer" if existing.get(name) is None else "outdated pointer"
            changes.append((pointer, expected[name], status))

    if write:
        for pointer, text, _ in changes:
            if text is None:
                pointer.unlink(missing_ok=True)
                pointer.parent.rmdir()
            else:
                pointer.parent.mkdir(parents=True, exist_ok=True)
                pointer.write_text(text, encoding="utf-8", newline="\n")
    return [f"{status}: {path.relative_to(root).as_posix()}" for path, _, status in changes]


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--check", action="store_true", help="report drift without writing (default)")
    mode.add_argument("--write", action="store_true", help="regenerate pointers and prune stale generated entries")
    args = parser.parse_args(argv)
    try:
        changes = sync(Path(__file__).resolve().parents[1], write=args.write)
    except (OSError, ValueError) as exc:
        print(f"Cannot sync skills: {exc}", file=sys.stderr)
        return 2
    for change in changes:
        print(change)
    if not changes:
        print("Skill pointers are current.")
    return int(bool(changes) and not args.write)


if __name__ == "__main__":
    raise SystemExit(main())
